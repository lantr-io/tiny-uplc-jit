package fromscalus

import uplc.*

/** The live demo: Scala source → Scalus → UPLC → our three engines (+ Scalus' production CEK).
  *
  * Usage: `sbt "scalusBridge/run [n]"`, e.g. `sbt "scalusBridge/run 20"`.
  */
object ScalusDemo:

    def main(args: Array[String]): Unit =
        val n = args.headOption.map(_.toInt).getOrElse(20)

        section("1. Scala")
        println("def fib(n: BigInt): BigInt = if n <= 1 then n else fib(n - 1) + fib(n - 2)")

        section("2. UPLC produced by Scalus")
        println(ScalusFib.scalusUplc.show)

        section("3. Scala code generated by the staged JIT")
        println(StagedJit.showCode(ScalusFib.fib))

        section(s"4. Race: fib $n")
        val term = ScalusFib.program(n)
        val rows = Engine.values.toList.map: engine =>
            val run = engine.prepare(term)
            val result = run().fold("-")(_.show)
            engine.label -> (Timing.measure(run), result)
        val scalusRow = "Scalus CEK (prod.)" ->
            (Timing.measure(() => ScalusFib.evaluateWithScalus(n)), ScalusFib.evaluateWithScalus(n).show)
        val all = rows :+ scalusRow
        val baseline = rows.head._2._1
        for (label, (micros, result)) <- all do
            println(f"$label%-20s ${micros}%10.1f µs/op ${baseline / micros}%6.1fx   $result")

    private def section(title: String): Unit =
        println()
        println(s"── $title " + "─" * math.max(0, 70 - title.length))
