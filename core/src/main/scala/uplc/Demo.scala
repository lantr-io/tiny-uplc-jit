package uplc

import scala.util.control.NonFatal

/** Demo on the hand-written examples, in three acts:
  *   1. show a UPLC program and the Scala code the staged compiler generates for it;
  *   2. race the three engines on it;
  *   3. show the price of native calls: deep recursion overflows the JVM stack.
  *
  * Usage: `sbt "core/run [fib|factorial|sumTo] [n]"`, e.g. `sbt "core/run fib 25"`. For `fib`
  * compiled from Scala by Scalus, see `fromscalus.ScalusDemo`.
  */
object Demo:

    def main(args: Array[String]): Unit =
        val name = args.headOption.getOrElse("fib")
        val n = args.lift(1).map(_.toInt).getOrElse(25)
        val term = Examples.program(name, n)

        section(s"1. UPLC program: $name $n")
        println(term.show)

        section("2. Scala code generated by the staged compiler")
        println(StagedJit.showCode(term))

        section("3. Race")
        val compileStart = System.nanoTime()
        StagedJit.compile(term) // the first compilation also loads the Scala compiler
        println(f"Staged compile (cold): ${(System.nanoTime() - compileStart) / 1e6}%.0f ms")
        val compileAgain = System.nanoTime()
        StagedJit.compile(term)
        println(f"Staged compile (warm): ${(System.nanoTime() - compileAgain) / 1e6}%.0f ms")
        println()

        val timings = Engine.values.toList.map: engine =>
            val run = engine.prepare(term)
            val result = run()
            val micros = Timing.measure(run)
            println(f"${engine.label}%-18s ${micros}%10.1f µs/op   result = ${result.fold("-")(_.show)}")
            engine -> micros
        val cek = timings.head._2
        println()
        for (engine, micros) <- timings.tail do
            println(f"${engine.label}%-18s ${cek / micros}%5.1fx faster than CEK")

        section("4. Pitfall: deep recursion (sumTo 100000)")
        val deep = Examples.program("sumTo", 100_000)
        for engine <- Engine.values do
            val outcome =
                try engine.prepare(deep)().fold("-")(_.show)
                catch
                    case _: StackOverflowError => "StackOverflowError!"
                    case NonFatal(e)           => e.toString
            println(f"${engine.label}%-18s $outcome")

    private def section(title: String): Unit =
        println()
        println(s"── $title " + "─" * math.max(0, 70 - title.length))
